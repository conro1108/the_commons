-- Repainting the ground counts as building. The painting is the plot's box, cell for cell.
create function the_commons.ground_built() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.ground is not null and length(new.ground) <> (select w * h from the_commons.plots where id = new.plot) then
    raise exception 'ground is the wrong size for plot %', new.plot using errcode = '23514';
  end if;
  if new.ground is distinct from old.ground then new.built_at := now(); end if;
  return new;
end $$;
create trigger filings_ground_built before update of ground on the_commons.filings
  for each row execute function the_commons.ground_built();

